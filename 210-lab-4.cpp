// using a for loop to output 1-100

#include <iostream>
using namespace std;

int main() {
    // complete this code in order to make it output
    // the numbers 1-100

    for (int i = 1; i <= 100; i++) // for loop for initializing i to 1, comparing to <= 100 and ++ for increment
    {
        cout << i << "\n";
    }
    return 0;
}